/** Research one freely reusable illustration for each narrative.
 * The article lead image is a candidate, never proof of permission. We require Commons
 * rights metadata, a compatible licence, source/artist credit, and a valid local raster.
 * Missing candidates and network failures are recorded without erasing verified assets.
 */
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
import {EnvHttpProxyAgent,fetch as networkFetch} from 'undici';
const proxyAgent=new EnvHttpProxyAgent();
const fetch=(url,options={})=>networkFetch(url,{...options,dispatcher:proxyAgent});
import {stories} from '../src/data.js';
import {storyImages} from '../src/image-manifest.js';
import {plainText,licenceFor,rasterType} from './image-rights.mjs';
const root=resolve(import.meta.dirname,'..');
const api={wikipedia:'https://en.wikipedia.org/w/api.php',commons:'https://commons.wikimedia.org/w/api.php'};
const now=new Date().toISOString();
const report={researchedAt:now,method:'Article lead image → Commons file rights metadata → local thumbnail. No fair-use or unknown licence is accepted.',records:[]};
const manifest={...storyImages};
const selections=JSON.parse(await readFile(resolve(root,'scripts/image-selections.json'),'utf8'));
const pause=ms=>new Promise(r=>setTimeout(r,ms));
const headers={'User-Agent':'TabiJapanHistoryAtlas/0.3 (https://github.com/omathurin/japan-map; illustration attribution research)','Accept':'application/json'};
await mkdir(resolve(root,'public/images'),{recursive:true});
await mkdir(resolve(root,'public/data'),{recursive:true});
class ResearchError extends Error{constructor(message,status=null){super(message);this.status=status}}
async function jsonRequest(base,params){
 const url=new URL(base);for(const[k,v]of Object.entries({...params,format:'json',formatversion:'2'}))url.searchParams.set(k,v);
 let response;try{response=await fetch(url,{headers,signal:AbortSignal.timeout(25000)})}catch(e){throw new ResearchError(`Network request to ${url.hostname} failed: ${e.message}`)}
 if(!response.ok)throw new ResearchError(`${url.hostname} returned HTTP ${response.status}`,response.status);
 const data=await response.json();if(data.error)throw new ResearchError(`${url.hostname}: ${data.error.code}`);return data;
}
async function saveReport(){
 report.summary={total:stories.length,illustrated:Object.keys(manifest).length,processedRecords:report.records.length,searched:report.records.filter(r=>r.status!=='blocked-before-search').length,byStatus:report.records.reduce((a,r)=>(a[r.status]=(a[r.status]||0)+1,a),{})};
 await writeFile(resolve(root,'public/data/image-research.json'),JSON.stringify(report,null,2)+'\n');
 await writeFile(resolve(root,'src/image-manifest.js'),'// Generated by scripts/research-images.mjs; source rights checked before inclusion.\nexport const storyImages = '+JSON.stringify(manifest,null,2)+';\n');
 const unique=new Map();for(const image of Object.values(manifest))unique.set(image.src,image);
 const md=s=>String(s||'').replaceAll('|','\\|').replace(/[\r\n]+/g,' ');
 const credits=['# Crédits et licences des illustrations','','Les images sont distribuées sous leurs licences individuelles, indépendamment du code de l’application. Consultez la notice Commons et les éventuelles restrictions avant réutilisation. Les miniatures sont affichées sans recadrage.','','| Fichier | Titre du document | Auteur / crédit fourni | Licence | Source |','| --- | --- | --- | --- | --- |'];
 for(const image of unique.values())credits.push(`| [${md(image.src.slice(9))}](${image.src.slice(9)}) | ${md(image.title)} | ${md(image.artist)} | [${md(image.license)}](${image.licenseUrl}) | [Notice et droits](${image.sourcePage}) |`);
 await writeFile(resolve(root,'public/images/CREDITS.md'),credits.join('\n')+'\n');
 console.log(JSON.stringify(report.summary,null,2));
}
try{
 // A single preflight prevents 145 repetitions of an unchanged policy denial.
 await Promise.all(Object.values(api).map(base=>jsonRequest(base,{action:'query',meta:'siteinfo',siprop:'general'})));
}catch(error){
 for(const s of stories)report.records.push({storyId:s.id,title:s.title,article:s.reference.url,status:'blocked-before-search',reason:error.message});
 await saveReport();console.error('Image research is blocked. Apply the required Wikipedia/Commons network domains, then rerun npm run images:research.');process.exitCode=2;
}
if(process.exitCode!==2){
 try{
 const titles=[...new Set(stories.map(s=>decodeURIComponent(new URL(s.reference.url).pathname.slice('/wiki/'.length))))];
 const articleImages=new Map(),normalizations=new Map();
 for(let i=0;i<titles.length;i+=35){
  const data=await jsonRequest(api.wikipedia,{action:'query',redirects:'1',prop:'pageimages',piprop:'name',pilicense:'free',titles:titles.slice(i,i+35).join('|')});
  for(const item of [...(data.query.normalized||[]),...(data.query.redirects||[])])normalizations.set(item.from,item.to);
  for(const page of data.query.pages||[])if(page.pageimage)articleImages.set(page.title,page.pageimage);
 }
 const normalizeTitle=t=>{let n=t.replaceAll('_',' '),seen=new Set();while(normalizations.has(n)&&!seen.has(n)){seen.add(n);n=normalizations.get(n)}return n};
 const candidates=new Map(stories.map(s=>[s.id,selections[s.id]?.file||articleImages.get(normalizeTitle(decodeURIComponent(new URL(s.reference.url).pathname.slice(6))))]));
 const files=[...new Set([...candidates.values()].filter(Boolean))];
 const information=new Map();
 for(let i=0;i<files.length;i+=30){
  const data=await jsonRequest(api.commons,{action:'query',redirects:'1',prop:'imageinfo',iiprop:'url|extmetadata|mime|timestamp|sha1',iiurlwidth:'240',iiextmetadatafilter:'Artist|LicenseShortName|LicenseUrl|Copyrighted|Copyright|Credit|ImageDescription|DateTimeOriginal|UsageTerms|Restrictions',titles:files.slice(i,i+30).map(f=>'File:'+f).join('|')});
  const redirects=new Map((data.query.redirects||[]).map(r=>[r.from,r.to]));
  for(const page of data.query.pages||[])if(page.imageinfo?.[0])information.set(page.title.replace(/^File:/,'').replaceAll('_',' '),{title:page.title,info:page.imageinfo[0]});
  for(const [from,to]of redirects){const found=information.get(to.replace(/^File:/,'').replaceAll('_',' '));if(found)information.set(from.replace(/^File:/,'').replaceAll('_',' '),found)}
 }
 const downloaded=new Map();
 for(const image of Object.values(manifest)){try{const title=decodeURIComponent(new URL(image.sourcePage).pathname.slice('/wiki/'.length));downloaded.set(title,{src:image.src,mime:image.mime,sha256:image.sha256,bytes:image.bytes})}catch{}}
 for(const s of stories){
  const file=candidates.get(s.id);const record={storyId:s.id,title:s.title,article:s.reference.url,candidate:file||null};
  try{
   if(!file){report.records.push({...record,status:'no-free-article-image'});continue}
   const entry=information.get(file.replaceAll('_',' '));if(!entry){report.records.push({...record,status:'no-commons-rights-record'});continue}
   const {info}=entry;
   const sourcePage='https://commons.wikimedia.org/wiki/'+encodeURIComponent(entry.title).replace(/^File%3A/,'File:');
   const rights=licenceFor(info,sourcePage);if(!rights){report.records.push({...record,status:'licence-not-approved'});continue}
   const meta=info.extmetadata||{};const artist=plainText(meta.Artist?.value);
   if(!artist&&rights.licenseFamily!=='PD'&&rights.licenseFamily!=='CC0'){report.records.push({...record,status:'missing-required-author'});continue}
   let asset=downloaded.get(entry.title);
   if(!asset){
    const remote=new URL(info.thumburl||info.url);
    // The publisher's long-standing upload.wikimedia.org /thumb/ endpoint serves the same thumbnail path.
    if(remote.hostname==='thumb.wikimedia.org'&&remote.pathname.startsWith('/wikipedia/commons/thumb/'))remote.hostname='upload.wikimedia.org';
    if(remote.protocol!=='https:'||!['upload.wikimedia.org','thumb.wikimedia.org'].includes(remote.hostname))throw new ResearchError('Unapproved image destination');
    await pause(1400);
    let response=await fetch(remote,{headers:{'User-Agent':headers['User-Agent'],'Accept':'image/*'},signal:AbortSignal.timeout(30000)});
    if(response.status===429){
     const requested=Number(response.headers.get('retry-after')||30);const delay=Math.min(60000,Math.max(30000,requested*1000));
     await response.body?.cancel();console.log(`Commons thumbnail rate limit: waiting ${delay/1000}s before one retry.`);await pause(delay);
     response=await fetch(remote,{headers:{'User-Agent':headers['User-Agent'],'Accept':'image/*'},signal:AbortSignal.timeout(30000)});
    }
    if(!response.ok){await response.body?.cancel();throw new ResearchError(`Thumbnail returned HTTP ${response.status}`,response.status);}
    const declared=Number(response.headers.get('content-length')||0);if(declared>350000){await response.body?.cancel();throw new ResearchError('Thumbnail exceeds the 350 kB local asset limit')};
    const reader=response.body.getReader();const chunks=[];let size=0;
    while(true){const{done,value}=await reader.read();if(done)break;size+=value.byteLength;if(size>350000){await reader.cancel();throw new ResearchError('Thumbnail exceeds the 350 kB local asset limit')}chunks.push(Buffer.from(value))}
    const bytes=Buffer.concat(chunks),type=rasterType(bytes);if(!type)throw new ResearchError('Downloaded content is not a supported raster image');
    const sha256=createHash('sha256').update(bytes).digest('hex');const filename=`commons-${sha256.slice(0,20)}.${type.extension}`;
    await writeFile(resolve(root,'public/images',filename),bytes);
    asset={src:`./images/${filename}`,mime:type.mime,sha256,bytes:bytes.length};downloaded.set(entry.title,asset);
   }
   manifest[s.id]={...asset,title:plainText(entry.title.replace(/^File:/,'').replaceAll('_',' ')),artist:artist||'Auteur non renseigné sur la fiche source',...rights,sourcePage,originalUrl:info.url,description:plainText(meta.ImageDescription?.value),date:plainText(meta.DateTimeOriginal?.value),credit:plainText(meta.Credit?.value),copyright:plainText(meta.Copyright?.value),usageTerms:plainText(meta.UsageTerms?.value),sourceFileTimestamp:info.timestamp,sourceFileSha1:info.sha1,verifiedAt:now,alt:`Document de référence pour « ${s.title} » : ${plainText(entry.title.replace(/^File:/,''))}`,modifications:'Miniature fournie par Wikimedia Commons ; affichage sans recadrage.',restrictions:plainText(meta.Restrictions?.value),context:selections[s.id]?.context||'Document associé au sujet de l’article ; il ne représente pas nécessairement l’événement à la date du curseur.',relevanceBasis:selections[s.id]?`Sélection éditoriale : ${selections[s.id].context}`:`Image libre de l’article de référence : ${s.reference.url}`};
   report.records.push({...record,status:'included',sourcePage,license:manifest[s.id].license,sha256:asset.sha256});
  }catch(error){report.records.push({...record,status:'download-or-network-error',reason:error.message})}
 }
 // Fallback search is recorded as candidates for human relevance review, never silently attached.
 for(const record of report.records.filter(r=>r.status==='no-free-article-image'||r.status==='no-commons-rights-record')){
  try{
   const s=stories.find(s=>s.id===record.storyId);const query=decodeURIComponent(new URL(s.reference.url).pathname.slice(6)).replaceAll('_',' ');
   const data=await jsonRequest(api.commons,{action:'query',list:'search',srnamespace:'6',srlimit:'3',srsearch:query});
   record.reviewCandidates=(data.query.search||[]).map(p=>({title:plainText(p.title),sourcePage:'https://commons.wikimedia.org/wiki/'+encodeURIComponent(p.title).replace(/^File%3A/,'File:')}));
   if(record.reviewCandidates.length)record.status='candidate-needs-relevance-review';
  }catch(error){record.fallbackSearchError=error.message}
 }
 await saveReport();
 }catch(error){
  const recorded=new Set(report.records.map(r=>r.storyId));
  for(const s of stories)if(!recorded.has(s.id))report.records.push({storyId:s.id,title:s.title,article:s.reference.url,status:'lookup-error',reason:error.message});
  await saveReport();process.exitCode=1;console.error('Research stopped after a lookup failure; completed records and existing verified assets were preserved.');
 }
}

proxyAgent.destroy();
